/**
 * What Sonic 3 A.I.R. accepts, as types and as data.
 *
 * The four payloads of the wasm-gaming engine contract, closed for this engine, and
 * {@link SONIC3AIR_SPEC} — the same thing as data the contract's base class reads:
 * every default lives there and nowhere else.
 */
import type { EnginePayloads, EngineSpec } from '@wasm-gaming/engine-specs';

/** Bytes, or a thunk that produces them only when the engine actually needs them. */
export type Sonic3AirAsset =
  | Uint8Array
  | ArrayBuffer
  | null
  | (() => Uint8Array | ArrayBuffer | null | Promise<Uint8Array | ArrayBuffer | null>);

/** Where the engine's files are. Fixed for the life of the page. */
export interface Sonic3AirConfig {
  /** The engine module (generated by the build). Defaults to `./sonic3air.js` next to the SDK. */
  jsUrl?: string;
  /** The official WebAssembly binary. Defaults to `./sonic3air.wasm` next to the SDK. */
  wasmUrl?: string;
  /** The engine's own data package. Defaults to `./sonic3air.data` next to the SDK. */
  dataUrl?: string;
}

/** The session. Nothing per-session: the game has its own menus. */
export type Sonic3AirOptions = Record<string, never>;

export interface Sonic3AirAssets {
  /**
   * The Sonic & Knuckles + Sonic 3 ROM (`Sonic_Knuckles_wSonic3.bin`, 4 MB, serial
   * MK-1563): the Steam release's file, or a Mega Drive dump of the lock-on. Required.
   */
  rom?: Sonic3AirAsset;
  /**
   * The remastered soundtrack (`audioremaster.bin`, ~130 MB, from the PC release or the
   * official web zip). Optional: without it the game plays the Mega Drive music.
   */
  audioremaster?: Sonic3AirAsset;
}

/** Where this engine's files live, and whether they outlive the page. */
export interface Sonic3AirStorage {
  /**
   * Per-game folder, relative to the engine's own: the game's save data (saves,
   * settings, mods) is mirrored to OPFS `sonic3air/<namespace>/`. Segments are cleaned
   * (`.`/`..` dropped, odd characters → `_`); a leading `sonic3air/` is stripped once.
   * `play.storagePath` gives the result.
   *
   * @defaultValue `"default"`
   */
  namespace?: string;
  /** `null` keeps nothing; otherwise the game's save data is mirrored to OPFS. */
  persist?: 'opfs' | null;
}

export interface Sonic3AirEvents {
  /** Save data changed and was written to (or removed from) `sonic3air/<namespace>/`. */
  saves: { files: string[]; removed: string[] };
}

export interface Sonic3AirPayloads extends EnginePayloads {
  config: Sonic3AirConfig;
  options: Sonic3AirOptions;
  assets: Sonic3AirAssets;
  storage: Sonic3AirStorage;
  events: Sonic3AirEvents;
}

/** The engine always draws 16:9 (its canvas is the window's width by 9/16 of it). */
